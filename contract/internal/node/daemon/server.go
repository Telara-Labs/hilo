var Version = "dev"

// LatestProtocolVersion is the modern revision implemented by this node.
const LatestProtocolVersion = "2026-07-28"

const LatestLegacyProtocolVersion = "2025-06-18"

func legacyProtocolVersion(proposed string) string {
	switch proposed {
	case "2024-11-05", "2025-03-26", LatestLegacyProtocolVersion:
		return proposed
	default:
		return LatestLegacyProtocolVersion
	}
}

type Request struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      json.RawMessage `json:"id,omitempty"`
	Method  string          `json:"method"`
	Params  json.RawMessage `json:"params,omitempty"`
	// OriginalID is populated only by the authenticated IPC parser, never by stdio.
	OriginalID json.RawMessage `json:"-"`
}
type Response struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      json.RawMessage `json:"id"`
	Result  any             `json:"result,omitempty"`
	Error   *RPCError       `json:"error,omitempty"`
}
type RPCError struct {
	Code    int    `json:"code"`
	Message string `json:"message"`
	Data    any    `json:"data,omitempty"`
}

// Backend must settle all transactions before Close returns. Calls receive only
// kernel-authenticated connections; Hello fields remain untrusted identity hints.
// Handle must drain the client's spool before resolving any memory scope.
// Close must be safe to retry after an error. Shutdown retains db.lock until
// Close succeeds; a failing adapter cannot hand ownership to a new writer.
type Backend interface {
	Handle(context.Context, ipc.Hello, Request) Response
	Close() error
}
type Opener func(context.Context) (Backend, error)
type Config struct {
	Paths ipc.Paths
	Open  Opener
	Ready func()
	// Verify revalidates managed startup authority under db.lock, before
	// invalidating prior settlement or opening any storage or listener.
	Verify func() error
}

func Error(id json.RawMessage, code string) Response {
	if len(id) == 0 {
		id = json.RawMessage("null")
	}
	return Response{JSONRPC: "2.0", ID: id, Error: &RPCError{Code: -32000, Message: code}}
}
func Parse(b []byte) (Request, error) {
	var r Request
	if !validateEnvelope(b) {
		return r, ipc.ErrFrame
	}
	if ipc.DecodeStrict(b, &r) != nil || r.JSONRPC != "2.0" || r.Method == "" {
		return r, ipc.ErrFrame
	}
	if len(r.ID) > 0 && !ValidRPCID(r.ID) {
		return r, ipc.ErrFrame
	}

	return r, nil
}
func Setup(r Request) (Response, bool) {
	out := Response{JSONRPC: "2.0", ID: r.ID}
	params, meta, err := RequestParams(r.Params)
	if err != nil {
		out.Error = &RPCError{Code: -32602, Message: err.Error()}
		return out, true
	}
	if meta.ProtocolVersion != "" && !supportedProtocolVersion(meta.ProtocolVersion) {
		out.Error = &RPCError{Code: -32022, Message: "Unsupported protocol version", Data: map[string]any{"requested": meta.ProtocolVersion, "supported": SupportedProtocolVersions()}}
		return out, true
	}
	if err := validateProtocolMetadata(r, meta); err != nil {
		out.Error = &RPCError{Code: -32602, Message: err.Error()}
		return out, true
	}
	switch r.Method {
	case "initialize":
		var p struct {
			ProtocolVersion string `json:"protocolVersion"`
		}
		if len(r.Params) > 0 && json.Unmarshal(params, &p) != nil {
			out.Error = &RPCError{Code: -32602, Message: "invalid_arguments"}
			return out, true
		}
		out.Result = map[string]any{"protocolVersion": legacyProtocolVersion(p.ProtocolVersion), "capabilities": capabilities(), "serverInfo": map[string]any{"name": "telara-memory", "version": Version}, "instructions": instructions}
		return out, true
	case "server/discover":
		if string(params) != "{}" {
			out.Error = &RPCError{Code: -32602, Message: "invalid_arguments"}
			return out, true
		}
		out.Result = map[string]any{"supportedVersions": SupportedProtocolVersions(), "capabilities": capabilities(), "_meta": map[string]any{"io.modelcontextprotocol/serverInfo": map[string]string{"name": "telara-memory", "version": Version}}, "instructions": instructions, "ttlMs": 3600000, "cacheScope": "public"}
		return out, true
	case "tools/list":
		if string(params) != "{}" {
			out.Error = &RPCError{Code: -32602, Message: "invalid_arguments"}
			return out, true
		}
		out.Result = map[string]any{"tools": mcpcatalog.Tools(), "ttlMs": 15000, "cacheScope": "private"}
		return out, true
	case "ping":
		out.Result = map[string]any{}
		return out, true
	}
	return out, false
}

type connectionKey struct{}

// ConnectionID is generated by the daemon, never supplied in MCP arguments.
func ConnectionID(ctx context.Context) string {
	value, _ := ctx.Value(connectionKey{}).(string)
	return value
}

func storeWired(backend Backend) bool {
	if state, ok := backend.(interface{ StoreWired() bool }); ok {
		return state.StoreWired()
	}
	return backend != nil
}

func Probe(ctx context.Context, p ipc.Paths) (Response, error) {
	ctx, cancel := context.WithTimeout(ctx, ipc.HandshakeTimeout)
	defer cancel()
	c, e := ipc.Dial(ctx, p)
	if e != nil {
		return Response{}, e
	}
	defer c.Close()
	pid, e := ipc.Peer(c)
	if e != nil {
		return Response{}, e
	}
	if deadline, ok := ctx.Deadline(); ok {
		if e = c.SetDeadline(deadline); e != nil {
			return Response{}, e
		}
	}
	h := ipc.Hello{T: "hello", V: ipc.WireVersion, Kind: "control", PID: os.Getpid(), Client: "status", NodeVersion: Version}
	if e = ipc.WriteFrame(c, h); e != nil {
		return Response{}, e
	}
	r := bufio.NewReader(c)
	b, e := ipc.ReadFrame(r)
	if e != nil {
		return Response{}, e
	}
	var ack struct {
		T string `json:"t"`
		V int    `json:"v"`
	}
	if json.Unmarshal(b, &ack) != nil || ack.T != "hello" || ack.V != ipc.WireVersion {
		return Response{}, ipc.ErrFrame
	}
	if e = ipc.WriteFrame(c, Request{JSONRPC: "2.0", ID: json.RawMessage("1"), Method: "status"}); e != nil {
		return Response{}, e
	}
	b, e = ipc.ReadFrame(r)
	if e != nil {
		return Response{}, e
	}
	var out Response
	e = json.Unmarshal(b, &out)
	if e != nil {
		return Response{}, e
	}
	if !validStatus(out, pid) {
		return Response{}, ipc.ErrFrame
	}
	return out, nil
}
func validStatus(out Response, pid int) bool {
	if out.JSONRPC != "2.0" || string(out.ID) != "1" || out.Error != nil {
		return false
	}
	fields, ok := out.Result.(map[string]any)
	if !ok {
		return false
	}
	return fields["state"] == "running" && fields["pid"] == float64(pid) && fields["resultType"] == "complete"
}
func Run(ctx context.Context, cfg Config) error {
	p := cfg.Paths
	if e := p.Prepare(); e != nil {
		return e
	}
	startup, cancelStartup := context.WithTimeout(ctx, ipc.HandshakeTimeout)
	defer cancelStartup()
	var start io.Closer
	var e error
	for {
		start, e = ipc.Lock(filepath.Join(p.Data, "start.lock"))
		if e == nil {
			break
		}
		if !errors.Is(e, ipc.ErrBusy) {
			return e
		}
		probe, cancel := context.WithTimeout(startup, 100*time.Millisecond)
		_, pe := Probe(probe, p)
		cancel()
		if pe == nil {
			return nil
		}
		select {
		case <-startup.Done():
			return startup.Err()
		case <-time.After(20 * time.Millisecond):
		}
	}
	defer start.Close()
	probe, cancel := context.WithTimeout(ctx, time.Second)
	_, e = Probe(probe, p)
	cancel()
	if e == nil {
		return nil
	}
	db, e := ipc.Lock(filepath.Join(p.Data, "db.lock"))
	if e != nil {
		return e
	}
	defer db.Close()
	if cfg.Verify != nil {
		if e = cfg.Verify(); e != nil {
			return e
		}
	}
	if e = writeSettlement(p, false); e != nil {
		return e
	}
	l, e := ipc.Listen(p)
	if e != nil {
		return e
	}
	defer l.Close()
	if e = ipc.RecordOwner(p); e != nil {
		return e
	}
	defer ipc.Cleanup(p)
	var backend Backend
	if cfg.Open != nil {
		backend, e = cfg.Open(ctx)
		if e != nil {
			return e
		}
	}
	life := &lifecycle{listener: l, active: map[net.Conn]bool{}}
	defer func() {
		if backend != nil {
			for backend.Close() != nil {
				time.Sleep(100 * time.Millisecond)
			}
		}
		life.settled(p)
	}()
	start.Close()
	var wg sync.WaitGroup
	slots := make(chan struct{}, 64)
	serving, cancelServing := context.WithCancel(ctx)
	defer cancelServing()
	done := make(chan struct{})
	defer close(done)
	go func() {
		select {
		case <-ctx.Done():
			l.Close()
			life.closeConnections()
		case <-done:
		}
	}()
	if cfg.Ready != nil {
		cfg.Ready()
	}
	var acceptErr error
	for {
		conn, err := l.Accept()
		if err != nil {
			if ctx.Err() != nil || life.isDraining() {
				break
			}
			var temporary interface{ Temporary() bool }
			if errors.As(err, &temporary) && temporary.Temporary() {
				select {
				case <-ctx.Done():
				case <-time.After(10 * time.Millisecond):
				}
				continue
			}
			acceptErr = err
			break
		}
		select {
		case slots <- struct{}{}:
		default:
			conn.Close()
			continue
		}
		if !life.admit(func() { life.active[conn] = true; wg.Add(1) }) {
			<-slots
			conn.Close()
			break
		}
		go func() {
			defer wg.Done()
			transferred := false
			defer func() {
				<-slots
				life.mu.Lock()
				delete(life.active, conn)
				life.mu.Unlock()
				if !transferred {
					conn.Close()
				}
			}()
			transferred = serve(serving, conn, backend, life)
		}()
	}
	if !life.isDraining() || ctx.Err() != nil {
		cancelServing()
		life.closeConnections()
	}
	// A drain does not cancel in-flight requests or close their response writers.
	wg.Wait()
	if acceptErr != nil {
		return acceptErr
	}
	return ctx.Err()
}

func serve(parent context.Context, c net.Conn, backend Backend, life *lifecycle) (transferred bool) {
	pid, e := ipc.Peer(c)
	if e != nil {
		return
	}
	ctx, cancel := context.WithCancel(parent)
	defer cancel()
	if c.SetDeadline(time.Now().Add(ipc.HandshakeTimeout)) != nil {
		return
	}
	if life.isDraining() {
		return
	}
	r := bufio.NewReader(c)
	b, e := ipc.ReadFrame(r)
	if e != nil {
		ipc.WriteFrame(c, map[string]string{"error": "invalid_frame"})
		return
	}
	var tag struct {
		T string `json:"t"`
	}
	json.Unmarshal(b, &tag)
	if tag.T == "nudge" {
		var n struct {
			T      string `json:"t"`
			V      int    `json:"v"`
			Client string `json:"client"`
		}
		if ipc.DecodeStrict(b, &n) == nil && n.V == 1 && n.Client != "" && !life.isDraining() {
			if wake, ok := backend.(interface{ Nudge(string) }); ok {
				wake.Nudge(n.Client)
			}
		}
		return
	}
	var h ipc.Hello
	if ipc.DecodeStrict(b, &h) != nil || !h.Valid() || h.PID != pid {
		ipc.WriteFrame(c, map[string]string{"error": "invalid_hello"})
		return
	}
	token := make([]byte, 16)
	if _, e = rand.Read(token); e != nil {
		return
	}
	ctx = context.WithValue(ctx, connectionKey{}, hex.EncodeToString(token))
	ctx = context.WithValue(ctx, peerPIDKey{}, pid)
	retirement := &connectionClose{}
	ctx = context.WithValue(ctx, closeKey{}, retirement)
	// This defer runs after the calls.Wait defer below, including cancellation,
	// normal EOF and shutdown. Backend implementations can retire adapter caches.
	defer func() {
		retirement.close()
		if hook, ok := backend.(interface{ ConnectionClosed(string) }); ok {
			hook.ConnectionClosed(ConnectionID(ctx))
		}
	}()
	if ipc.WriteFrame(c, map[string]any{"t": "hello", "v": ipc.WireVersion, "connection_id": ConnectionID(ctx)}) != nil {
		return
	}
	if c.SetDeadline(time.Time{}) != nil {
		return
	}
	if life.isDraining() {
		return
	}
	var writeMu sync.Mutex
	write := func(v any) error {
		writeMu.Lock()
		defer writeMu.Unlock()
		if e := c.SetWriteDeadline(time.Now().Add(ipc.HandshakeTimeout)); e != nil {
			cancel()
			c.Close()
			return e
		}
		e := ipc.WriteFrame(c, v)
		if e != nil {
			cancel()
			c.Close()
		}
		return e
	}
	slots := make(chan struct{}, ipc.MaxInFlight)
	var calls sync.WaitGroup
	var pending Inflight
	defer func() {
		if !life.isDraining() {
			cancel()
		}
		calls.Wait()
		cancel()
	}()
	for {
		b, e = ipc.ReadFrame(r)
		if e != nil {
			if !life.isDraining() {
				if !errors.Is(e, io.EOF) {
					write(map[string]string{"error": "invalid_frame"})
				}
				cancel()
			}
			return
		}
		if life.isDraining() {
			return
		}
		req, e := parseForwarded(b)
		if e != nil {
			write(map[string]string{"error": "invalid_request"})
			cancel()
			return
		}
		if len(req.ID) == 0 {
			if id, ok := CancellationID(req); ok {
				pending.Cancel(id)
			}
			continue
		}
		if req.Method == "drain-and-exit" {
			// The kernel peer and hello PID have already been verified. MCP callers,
			// forwarded request envelopes and nonempty params cannot invoke control.
			if h.Kind != "control" || len(req.OriginalID) != 0 || (len(req.Params) > 0 && string(req.Params) != "{}") {
				if write(Error(req.ID, "unsupported_control")) != nil {
					return
				}
				continue
			}
			if life.drain(c, req.ID) {
				return true
			}
			write(Error(req.ID, "draining"))
			return
		}
		if life.isDraining() {
			return
		}
		// Setup and health checks never wait behind a store transaction or its
		// admission slots. The shim uses the same handler without opening IPC.
		if out, ok := Setup(req); ok {
			if write(out) != nil {
				return
			}
			continue
		}
		select {
		case slots <- struct{}{}:
		default:
			if write(Error(req.ID, "busy")) != nil {
				return
			}
			continue
		}
		flight, ok := pending.Begin(ctx, req.ID)
		if !ok {
			<-slots
			// A duplicate active ID cannot identify a second call safely.
			cancel()
			return
		}
		if !life.admit(func() { calls.Add(1) }) {
			flight.Finish()
			<-slots
			return
		}
		go func(req Request, flight *Flight) {
			defer calls.Done()
			defer flight.Finish()
			defer func() { <-slots }()
			var out Response
			if req.Method == "status" {
				out = Response{JSONRPC: "2.0", ID: req.ID, Result: map[string]any{"state": "running", "pid": os.Getpid(), "store_wired": storeWired(backend), "autostart": "reported_by_install_status"}}
			} else if h.Kind != "mcp" {
				out = Error(req.ID, "unsupported_control")
			} else if backend == nil {
				out = Error(req.ID, "store_unavailable")
			} else {
				out = backend.Handle(flight.Context, h, req)
				out.JSONRPC = "2.0"
				out.ID = req.ID
			}
			flight.Reply(func() { write(out) })
		}(req, flight)
	}
}
